import assert from 'node:assert/strict';
import {build} from 'esbuild';
const origin='http://localhost:5173';
const login=await fetch(origin+'/signin-with-chatgpt?return_to=/',{redirect:'manual'});
const cookie=login.headers.get('set-cookie').split(';')[0];
const call=async(body,headers={})=>{const r=await fetch(origin+'/api/settings',{method:body?'PUT':'GET',headers:{Cookie:cookie,...(body?{'Content-Type':'application/json'}:{}),...headers},...(body?{body:JSON.stringify(body)}:{})});return{status:r.status,data:await r.json()};};
assert.equal((await fetch(origin+'/api/settings')).status,401);
const original=(await call()).data.preferences;
const edited=structuredClone(original);edited.fontFamily='Verdana, sans-serif';edited.shortcuts.addChild='Alt+Enter';edited.spelling=false;
assert.equal((await call({preferences:edited})).status,200);
assert.deepEqual((await call()).data.preferences,edited,'cloud settings survive a separate request');
assert.equal((await call({preferences:edited},{'Sec-Fetch-Site':'cross-site'})).status,403);
assert.equal((await call({preferences:original})).status,200,'original test preferences restored');
await build({entryPoints:['src/services/preferences.ts'],outfile:'.sites-runtime/test-preferences.mjs',bundle:true,platform:'node',format:'esm'});
const {DEFAULT_PREFERENCES,shortcutFromEvent,commandForEvent}=await import('../.sites-runtime/test-preferences.mjs');
const event=(key,code,mod={})=>({key,code,ctrlKey:false,metaKey:false,altKey:false,shiftKey:false,...mod});
assert.equal(commandForEvent(event('Enter','Enter'),DEFAULT_PREFERENCES),'addChild');
assert.equal(commandForEvent(event('Tab','Tab'),DEFAULT_PREFERENCES),'addSibling');
assert.equal(commandForEvent(event('Enter','Enter',{altKey:true}),edited),'addChild');
assert.equal(shortcutFromEvent(event('!','Digit1',{shiftKey:true})),'Shift+1');
await build({entryPoints:['src/utils/text.ts'],outfile:'.sites-runtime/test-text.mjs',bundle:true,platform:'node',format:'esm'});
const {measureNode,wrapText}=await import('../.sites-runtime/test-text.mjs');
const node={id:'a',text:'Short idea',parentId:null,childrenIds:[]};
const small=measureNode(node,false,'underline');
const long=measureNode({...node,text:'A long paragraph that must wrap and grow without clipping. '.repeat(20)},false,'underline');
assert.ok(long.height>small.height*4);
assert.ok(long.width<=320);
const hard=wrapText('X'.repeat(200),20,s=>s.length);
assert.equal(hard.join(''),'X'.repeat(200));assert.ok(hard.every(s=>s.length<=20));
assert.deepEqual(wrapText('One\n\nThree',100,s=>s.length),['One','','Three']);
assert.ok(measureNode({...node,text:'First\nSecond\nThird'},false,'underline').height>=3*small.lineHeight);
console.log('PASS: authenticated settings persistence, cross-site protection, configurable shortcuts, default Enter child / Tab sibling, wrapped paragraphs, hard line breaks, and long unbroken text.');
